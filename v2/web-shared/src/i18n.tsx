const instance = i18next.createInstance()
void instance.init({
  resources: { "en-US": { translation: enUS }, "zh-CN": { translation: zhCN } },
  lng: "en-US",
  fallbackLng: "en-US",
  interpolation: { escapeValue: false },
  returnNull: false,
})

function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem(storageKey)
    if (stored === "zh-CN" || stored === "en-US") return stored
  } catch { /* preferences are best effort */ }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US"
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, updateLocale] = useState<Locale>(initialLocale)
  if (instance.language !== locale) void instance.changeLanguage(locale)
  const setLocale = useCallback((next: Locale) => {
    updateLocale(next)
    void instance.changeLanguage(next)
    document.documentElement.lang = next
    try { localStorage.setItem(storageKey, next) } catch { /* preferences are best effort */ }
  }, [])
  useEffect(() => { document.documentElement.lang = locale }, [locale])
  const value = useMemo(() => ({ locale, setLocale }), [locale, setLocale])
  return <LocaleContext.Provider value={value}><I18nextProvider i18n={instance}>{children}</I18nextProvider></LocaleContext.Provider>
}

const LocaleContext = createContext<{ locale: Locale; setLocale: (locale: Locale) => void } | null>(null)
export function useLocale() {
  const value = useContext(LocaleContext)
  if (!value) throw new Error("useLocale must be used inside I18nProvider.")
  return value
}
